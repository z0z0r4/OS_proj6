#!/usr/bin/perl -w

# Generate usys.S, the stubs for syscalls.

print "# generated by usys.pl - do not edit\n";

print "#include \"kernel/syscall.h\"\n";

sub entry {
    my $prefix = "sys_";
    my $name = shift;
    if ($name eq "sbrk") {
	print ".global $prefix$name\n";
	print "$prefix$name:\n";
    } else {
	print ".global $name\n";
	print "$name:\n";
    }
    print "#ifdef ARCH_LOONGARCH\n";
    print " li.d \$a7, SYS_${name}\n";
    print " syscall 0\n";
    print " jirl \$zero, \$ra, 0\n";
    print "#else\n";
    print " li a7, SYS_${name}\n";
    print " ecall\n";
    print " ret\n";
    print "#endif\n";
}
	
entry("fork");
entry("exit");
entry("wait");
entry("pipe");
entry("read");
entry("write");
entry("close");
entry("kill");
entry("exec");
entry("open");
entry("mknod");
entry("unlink");
entry("fstat");
entry("link");
entry("mkdir");
entry("chdir");
entry("dup");
entry("getpid");
entry("mount");
entry("umount");
